"""
be_analysis.py -- WHY does backward Euler (BE) inside the classical adjoint hurt the inversion so much, when the
forward temperatures it produces are almost the same as Crank-Nicolson's?

Theory being tested
  One BE step multiplies a mode of decay rate lambda by 1/(1 + x), x = lambda * dt; the exact factor is exp(-x).
  Since 1 + x < exp(x), BE always decays SLOWER than the true equation. To first order
      (1 + x)^(-n) = exp(-lambda t (1 - x/2 + ...)),
  i.e. BE behaves like the exact equation with D replaced by D (1 - lambda dt / 2). To reproduce the same readings
  an inversion using BE must therefore INFLATE D by about lambda dt / 2. CN's per-step error is O(x^3), so its
  effective-D error is O(x^2 / 12): negligible.
  The change in u is small in absolute terms, but what matters is (i) how it compares with the noise sigma, and
  (ii) how weakly u depends on D (a small du corresponds to a large dD).

Tests
  T1 forward error of each integrator at the actual readings (true D, no inversion), in % of signal and in sigma
  T2 sensitivity of u to D, and the constant rescaling c* of D that makes each integrator reproduce the reference;
     compared with the first-order prediction lambda_bar dt / 2
  T3 direction of the bias in the Study 5 inversions: mean(D_hat) / mean(D_true), BE vs CN
  T4 the discrepancy principle: when the integrator bias exceeds sigma the stopping rule cannot fire correctly
  T5 causal test: data generated BY the BE-100 forward (same noise draw) inverted WITH BE-100. If the error falls to
     CN's level, the damage is the data/solver mismatch, not BE as an inversion method.

  python run.py study5_time_integrators/be_analysis.py            (from extended_studies/)
Writes study5_time_integrators/be_analysis.md, be_analysis.json, fig_be_mechanism.png/.pdf
"""
import copy
import json
import time
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.optimize import minimize_scalar

import adjoint_inversion as A
import solvers as S
from run_study import dataset, KEYS

HERE = Path(__file__).resolve().parent
DENSE = "A_smooth__Fo0.1__uniform8__n3969__nodes_nested__eta0.01"
REF = ("CN", 4800)
VARIANTS = [("BE", 100), ("BE", 200), ("CN", 100), ("CN", 200)]
OUT = {}


def log(*a):
    print(*a, flush=True)


def fwd(solver, D):
    return solver.predict(solver.forward(D)[0])


# ----------------------------------------------------------------------------------------------- T1
def t1(ds, D, ref_u, sig):
    rows = []
    t = ds.t
    times = np.unique(np.round(t, 8))
    for name, n in VARIANTS:
        s = S.make(name, ds, n)
        u = fwd(s, D)
        d = u - ref_u
        r = dict(solver=f"{name} {n}", dt=float(ds.T / n),
                 rel_err_pct=float(100 * np.sqrt(np.mean(d ** 2)) / np.sqrt(np.mean(ref_u ** 2))),
                 max_abs_err=float(np.abs(d).max()),
                 mean_signed_over_sigma1=float(d.mean() / sig[0.01]),
                 frac_too_warm=float(np.mean(d > 0)))
        for eta, sg in sig.items():
            r[f"rms_over_sigma_{eta:g}"] = float(np.sqrt(np.mean(d ** 2)) / sg)
        r["by_time_over_sigma1"] = [float(np.sqrt(np.mean(d[np.isclose(t, tt)] ** 2)) / sig[0.01]) for tt in times]
        rows.append(r)
        log(f"  T1 {name} {n}: u error {r['rel_err_pct']:.3f} % of signal = {r['rms_over_sigma_0.01']:.2f} sigma(1%), "
            f"{r['rms_over_sigma_0.05']:.2f} sigma(5%); too warm at {100 * r['frac_too_warm']:.0f} % of readings")
    return rows, times


# ----------------------------------------------------------------------------------------------- T2
def t2(ds, D, ref_u, sig, ref):
    out = {}
    # sensitivity: change of u when D changes by 1 % and 10 %
    for pct in (1, 10):
        du = fwd(ref, D * (1 + pct / 100)) - ref_u
        out[f"du_for_D_plus_{pct}pct_over_sigma1"] = float(np.sqrt(np.mean(du ** 2)) / sig[0.01])
        out[f"du_for_D_plus_{pct}pct_rel_pct"] = float(100 * np.sqrt(np.mean(du ** 2)) / np.sqrt(np.mean(ref_u ** 2)))
    log(f"  T2 sensitivity: D +1 % moves u by {out['du_for_D_plus_1pct_rel_pct']:.3f} % of signal "
        f"({out['du_for_D_plus_1pct_over_sigma1']:.2f} sigma at 1 % noise)")
    # effective decay rate of the clean signal between reading times (dominant modes)
    times = np.unique(np.round(ds.t, 8))
    amp = np.array([np.sqrt(np.mean(ref_u[np.isclose(ds.t, tt)] ** 2)) for tt in times])
    lam = -np.polyfit(times, np.log(amp), 1)[0]
    out["lambda_bar"] = float(lam)
    comp = []
    for name, n in VARIANTS:
        s = S.make(name, ds, n)
        f = lambda c: float(np.sum((fwd(s, c * D) - ref_u) ** 2))
        res = minimize_scalar(f, bounds=(0.8, 1.25), method="bounded", options={"xatol": 1e-5})
        c = float(res.x)
        resid = float(np.sqrt(res.fun / len(ref_u)) / sig[0.01])
        dt = ds.T / n
        pred = (lam * dt / 2) if name == "BE" else (lam * dt) ** 2 / 12
        comp.append(dict(solver=f"{name} {n}", c_star=c, D_shift_pct=100 * (c - 1), predicted_pct=100 * pred,
                         resid_after_over_sigma1=resid))
        log(f"  T2 {name} {n}: needs D x {c:.4f} ({100 * (c - 1):+.2f} %); first-order prediction "
            f"{100 * pred:+.2f} %; leftover after rescaling {resid:.2f} sigma(1%)")
    out["compensation"] = comp
    return out


# ----------------------------------------------------------------------------------------------- T3, T4
def t3_t4():
    tab = pd.read_csv(HERE / "results_table.csv")
    rows = []
    for key in KEYS:
        ds = dataset(key)
        D_true = ds.ground_truth()[0]
        for name in ("BE", "CN"):
            p = HERE / "results" / "B" / f"{name}_100" / key
            if not (p / "D_hat.npz").exists():
                continue
            Dh = np.load(p / "D_hat.npz")["D_hat"]
            m = json.load(open(p / "metrics.json"))
            rows.append(dict(solver=name, n_sensors=ds.n_sensors if hasattr(ds, "n_sensors") else int(key.split("__n")[1].split("__")[0]),
                             eta=float(key.split("eta")[1]), mean_ratio=float(Dh.mean() / D_true.mean()),
                             median_log_ratio_pct=float(100 * np.median(np.log(Dh.ravel() / D_true.ravel()))),
                             rel_L2_D=m["rel_L2_D"], alpha=m["alpha"], flag=m["flag"]))
    return pd.DataFrame(rows)


# ----------------------------------------------------------------------------------------------- T5
def t5(cache):
    rows = []
    cells = [(50, 0.01), (400, 0.01), (3969, 0.01), (3969, 0.05)]
    for n, eta in cells:
        key = f"A_smooth__Fo0.1__uniform8__n{n}__nodes_nested__eta{eta:g}"
        ds = dataset(key)
        D_true, u_clean = ds.ground_truth()
        noise = ds.u - u_clean                                  # the dataset's own noise draw
        be = S.make("BE", ds, 100)
        u_be = fwd(be, D_true.ravel())                          # what a BE-100 world would have measured
        ds2 = copy.copy(ds)
        ds2.u = u_be + noise
        s = S.make("BE", ds2, 100)
        t0 = time.perf_counter()
        r = s.invert(verbose=False)
        rel = float(np.linalg.norm(r["D"].ravel() - D_true.ravel()) / np.linalg.norm(D_true.ravel()))
        m_be = json.load(open(HERE / "results" / "B" / "BE_100" / key / "metrics.json"))
        m_cn = json.load(open(HERE / "results" / "B" / "CN_100" / key / "metrics.json"))
        row = dict(n_sensors=n, eta=eta, BE_on_real_data=m_be["rel_L2_D"], CN_on_real_data=m_cn["rel_L2_D"],
                   BE_on_BE_data=rel, flag=r["flag"], alpha=float(r["alpha"]), wall_s=time.perf_counter() - t0)
        rows.append(row)
        log(f"  T5 n={n} eta={eta:g}: BE on real (RK4) data {row['BE_on_real_data']:.4f} | CN on real data "
            f"{row['CN_on_real_data']:.4f} | BE on BE-generated data {rel:.4f}  ({r['flag']}, {row['wall_s']:.0f} s)")
        cache.append(row)
        json.dump(cache, open(HERE / "be_analysis_t5_partial.json", "w"), indent=1)
    return rows


# ----------------------------------------------------------------------------------------------- figure
def figure(t1rows, times, sig, t2out, t5rows):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    INK2, GRID = "#52514e", "#e4e3df"
    BLUE, VIOLET, GREY, ORANGE = "#2a78d6", "#6250d6", "#8a8984", "#eb6834"
    plt.rcParams.update({"font.size": 12, "axes.spines.top": False, "axes.spines.right": False, "axes.grid": True,
                         "grid.color": GRID, "axes.axisbelow": True, "legend.frameon": False, "lines.linewidth": 2})
    fig, ax = plt.subplots(1, 3, figsize=(17, 4.8))

    x = np.logspace(-3, 0, 300)
    ax[0].plot(x, 100 * (np.log1p(x) / x - 1), color=VIOLET, label="backward Euler: ln(1+x)/x")
    ax[0].plot(x, 100 * (np.log((1 + x / 2) / (1 - x / 2)) / x - 1), color=BLUE, label="Crank-Nicolson")
    dt = 0.363636 / 100
    for k, mk in ((1, "o"), (2, "s"), (3, "^"), (4, "D")):
        xk = 0.275 * np.pi ** 2 * 2 * k ** 2 * dt
        yk = 100 * (np.log1p(xk) / xk - 1)
        ax[0].plot(xk, yk, mk, color=VIOLET, ms=9, mec="white", mew=1.2, zorder=3)
        ax[0].annotate(f"mode ({k},{k})\n{yk:+.1f} %", (xk, yk), textcoords="offset points", xytext=(-8, -30),
                       fontsize=9.5, color=INK2, ha="center")
    ax[0].axhline(0, color=GREY, lw=1)
    ax[0].set_xscale("log"); ax[0].set_ylim(-32, 6); ax[0].set_xlim(1e-3, 1)
    ax[0].set_xlabel(r"$x = \lambda\,\Delta t$   (mode decay rate x time step)")
    ax[0].set_ylabel("effective D the scheme mimics,\nvs true D (%)")
    ax[0].set_title("(a) BE acts like a smaller D (markers: 100 steps)")
    ax[0].legend(loc="lower left", fontsize=10)

    tt = times
    for r, col, ls in ((t1rows[0], VIOLET, "-"), (t1rows[1], VIOLET, "--"), (t1rows[2], BLUE, "-")):
        ax[1].plot(tt, r["by_time_over_sigma1"], ls, marker="o", color=col, label=r["solver"] + " steps", ms=6)
    ax[1].axhline(1, color=GREY, lw=1.2); ax[1].text(tt[-1], 1.12, "noise level at 1 %", color=INK2, fontsize=10, ha="right")
    ax[1].axhline(sig[0.05] / sig[0.01], color=GREY, lw=1.2, ls=":")
    ax[1].text(tt[-1], sig[0.05] / sig[0.01] * 1.12, "noise level at 5 %", color=INK2, fontsize=10, ha="right")
    ax[1].set_yscale("log")
    ax[1].set_xlabel("reading time"); ax[1].set_ylabel(r"forward error at sensors / $\sigma_{1\%}$")
    ax[1].set_title("(b) the error is small, but not small vs the noise")
    ax[1].legend(loc="lower left")

    labels = [f"{r['n_sensors']}\n{int(100 * r['eta'])} %" for r in t5rows]
    xi = np.arange(len(t5rows)); w = 0.26
    for k, (field, col, lab) in enumerate((("BE_on_real_data", VIOLET, "BE on real data"),
                                           ("BE_on_BE_data", "#b3a9ec", "BE on BE-made data"),
                                           ("CN_on_real_data", BLUE, "CN on real data"))):
        v = [r[field] for r in t5rows]
        ax[2].bar(xi + (k - 1) * w, v, w * 0.92, color=col, label=lab)
        for xx, vv in zip(xi + (k - 1) * w, v):
            ax[2].text(xx, vv + 0.002, f"{vv:.3f}", ha="center", fontsize=9, color="#0b0b0b")
    ax[2].set_xticks(xi); ax[2].set_xticklabels(labels); ax[2].set_xlabel("sensors, noise")
    ax[2].set_ylabel("relL2(D)"); ax[2].set_title("(c) remove the mismatch and BE recovers")
    ax[2].grid(axis="x", visible=False); ax[2].legend(loc="upper right", fontsize=10)
    fig.tight_layout()
    fig.savefig(HERE / "fig_be_mechanism.png", dpi=160); fig.savefig(HERE / "fig_be_mechanism.pdf")
    log("  wrote fig_be_mechanism.png")


def main():
    t0 = time.perf_counter()
    ds = dataset(DENSE)
    D_true, u_clean = ds.ground_truth()
    D = D_true.ravel()
    sig = {eta: ds.sigma / 0.01 * eta for eta in (0.01, 0.05, 0.1)}     # sigma = eta x signal RMS
    ref = S.make(REF[0], ds, REF[1])
    ref_u = fwd(ref, D)
    floor = float(np.sqrt(np.mean((ref_u - u_clean) ** 2)) / sig[0.01])
    log(f"T1 forward error (true D, 3,969 sensors x 8 times; reference CN 4800). Grid floor (65^2 vs RK4 129^2 data): "
        f"{floor:.2f} sigma(1%)")
    t1rows, times = t1(ds, D, ref_u, sig)
    log("T2 sensitivity and compensation")
    t2out = t2(ds, D, ref_u, sig, ref)
    log("T3/T4 Study 5 inversions")
    t34 = t3_t4()
    log(t34.to_string(index=False))
    log("T5 causal test (4 inversions)")
    t5rows = t5([])
    figure(t1rows, times, sig, t2out, t5rows)
    OUT.update(grid_floor_over_sigma1=floor, sigma=sig, T1=t1rows, T2=t2out, T34=t34.to_dict("records"), T5=t5rows,
               wall_s=time.perf_counter() - t0)
    json.dump(OUT, open(HERE / "be_analysis.json", "w"), indent=1)
    log(f"done in {time.perf_counter() - t0:.0f} s")


if __name__ == "__main__":
    import sys
