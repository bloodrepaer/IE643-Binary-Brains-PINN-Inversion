"""
summarise.py -- tables and figures from study5 results (reads results/*/*/*/metrics.json only).

Writes, next to this file:
  results_table.csv        one row per run
  RESULTS.md               the tables in Markdown
  fig_error_vs_density.png relL2(D) vs sensors, one panel per noise level, one line per solver/step
  fig_replay_vs_density.png replay under the common accurate solver (CN 4,800 steps) / sigma
Run from extended_studies/:  python run.py study5_time_integrators/summarise.py
"""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

HERE = Path(__file__).resolve().parent
COLS = ["block", "solver", "n_steps", "n_sensors", "eta", "rel_L2_D", "rmse_logD", "replay_own_over_sigma",
        "replay_common_CN4800_over_sigma", "flag", "alpha", "total_iters", "n_evals", "wall_s", "D_max", "hit_cap",
        "const_rel_L2_D", "key"]
STYLE = {("RK4", 4800): ("#1b7837", "-", "o"), ("CN", 4800): ("#2166ac", "-", "s"), ("BE", 4800): ("#b2182b", "-", "^"),
         ("CN", 200): ("#67a9cf", "--", "s"), ("BE", 200): ("#ef8a62", "--", "^"),
         ("CN", 100): ("#9ecae1", ":", "s"), ("BE", 100): ("#fdae6b", ":", "^")}


def load():
    rows = [json.loads(p.read_text()) for p in sorted((HERE / "results").glob("*/*/*/metrics.json"))]
    if not rows:
        raise SystemExit("no results yet")
    return pd.DataFrame(rows)[COLS].sort_values(["eta", "n_sensors", "block", "solver", "n_steps"])


def pivot(df, value, fmt):
    df = df.assign(arm=df["solver"] + " " + df["n_steps"].astype(str))
    order = [f"{s} {n}" for s, n in STYLE if f"{s} {n}" in set(df["arm"])]
    t = df.pivot_table(index=["eta", "n_sensors"], columns="arm", values=value, aggfunc="first")[order]
    t.index = [f"{e * 100:g} % / {n}" for e, n in t.index]
    t.index.name = "noise / sensors"
    return t.map(lambda v: "" if pd.isna(v) else fmt.format(v))


def figure(df, value, ylabel, path, ref_line=None):
    etas = sorted(df["eta"].unique())
    fig, axes = plt.subplots(1, len(etas), figsize=(4.6 * len(etas), 3.8), sharey=True)
    axes = [axes] if len(etas) == 1 else axes
    for ax, eta in zip(axes, etas):
        d = df[df["eta"] == eta]
        for (s, n), (c, ls, mk) in STYLE.items():
            g = d[(d["solver"] == s) & (d["n_steps"] == n)].sort_values("n_sensors")
            if len(g):
                ax.plot(g["n_sensors"], g[value], ls=ls, marker=mk, color=c, label=f"{s}, {n} steps")
        if ref_line is not None:
            ax.axhline(ref_line, color="0.5", lw=0.8)
        ax.set_xscale("log"); ax.set_title(f"noise {eta * 100:g} %"); ax.set_xlabel("sensors")
        ax.grid(alpha=0.3, which="both")
    axes[0].set_ylabel(ylabel)
    axes[-1].legend(fontsize=8, frameon=False)
    fig.tight_layout(); fig.savefig(path, dpi=150); plt.close(fig)


def main():
    df = load()
    df.to_csv(HERE / "results_table.csv", index=False)
    figure(df, "rel_L2_D", "relL2(D)", HERE / "fig_error_vs_density.png")
    figure(df, "replay_common_CN4800_over_sigma", "replay RMS / sigma (CN, 4,800 steps)",
           HERE / "fig_replay_vs_density.png", ref_line=1.0)
    md = ["# Study 5 results (generated by summarise.py)", "",
          f"{len(df)} runs. relL2(D) on the 65 x 65 grid; lower is better.", "",
          "## relL2(D)", "", pivot(df, "rel_L2_D", "{:.4f}").to_markdown(), "",
          "## Replay under the common accurate solver (CN, 4,800 steps), RMS / sigma", "",
          pivot(df, "replay_common_CN4800_over_sigma", "{:.2f}").to_markdown(), "",
          "## Replay under the run's own solver, RMS / sigma", "",
          pivot(df, "replay_own_over_sigma", "{:.2f}").to_markdown(), "",
          "## Discrepancy-principle outcome", "", pivot(df, "flag", "{}").to_markdown(), ""]
    (HERE / "RESULTS.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
