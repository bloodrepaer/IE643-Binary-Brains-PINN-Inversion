def prepare(size, paired_only=True):
    gate=C.HOME/"pinn_review_gate.json"
    if gate.exists() and json.loads(gate.read_text()).get("status")!="open":
        print("New PINN batches held for constraint/state-model review; see campaign/pinn_review_gate.json")
        return
    jobs=json.loads((C.HOME/"jobs.json").read_text())
    lookup={(j["collection"],j["key"],j["method"]):j for j in jobs}
    remotes=C.HOME/"remote";remotes.mkdir(exist_ok=True)
    existing=[json.loads(p.read_text()) for p in remotes.glob("batch_*.json")]
    active=[r for r in existing if r["status"] in ("prepared","submitted","running")]
    if active:
        print("Existing batch must be resolved first:",active[0]);return
    previously_failed={i for r in existing if r["status"]=="imported" for i in r.get("failed_ids",[])}
    eligible=[j for j in jobs if j["method"]=="pinn" and not C.completed(j) and j["id"] not in previously_failed]
    if paired_only:
        eligible=[j for j in eligible if C.completed(lookup[(j["collection"],j["key"],"adjoint_nn")])]
    selected=eligible[:size]
    if not selected:
        print("No eligible PINN cases yet; wait for adjoint results or inspect failures");return
    number=len(existing)+1;batch=f"batch_{number:04d}"
    folder=C.HOME/"kernels"/batch;folder.mkdir(parents=True,exist_ok=True)
    slug=f"mihirgune123/ie643-neural-campaign-{number:04d}"
    C.atomic_json(folder/"kernel-metadata.json",dict(id=slug,title=f"IE643 neural campaign {number:04d}",
        code_file="run_batch.py",language="python",kernel_type="script",is_private=True,enable_gpu=True,
        enable_internet=False,dataset_sources=[DATASET],competition_sources=[],kernel_sources=[]))
    (folder/"run_batch.py").write_text(TEMPLATE.replace("__JOB_IDS__",repr([j["id"] for j in selected])),encoding="utf-8")
    record=dict(batch=batch,kernel=slug,status="prepared",job_ids=[j["id"] for j in selected],
                folder=str(folder.relative_to(C.ROOT)),created=C.now(),timeout_seconds=7200)
    C.atomic_json(remotes/(batch+".json"),record)
    print(json.dumps(record,indent=2))


def ingest(batch,archive):
    record_path=C.HOME/"remote"/(batch+".json")
    record=json.loads(record_path.read_text())
    jobs={j["id"]:j for j in json.loads((C.HOME/"jobs.json").read_text())}
    with zipfile.ZipFile(archive) as z:
        status=json.loads(z.read("campaign/remote_status.json"))
        allowed=[jobs[i]["output"].replace("\\","/")+"/" for i in record["job_ids"]]
        for name in z.namelist():
            if any(name.startswith(prefix) for prefix in allowed):
                target=(C.ROOT/name).resolve()
                if not target.is_relative_to(C.HOME.resolve()):raise ValueError("Output leaves campaign folder")
                if target.exists() and target.read_bytes()!=z.read(name):
                    raise RuntimeError(f"Conflicting saved artifact: {target}")
                target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(z.read(name))
            elif name.startswith("campaign/logs/"):
                name_path=Path(name)
                if name_path.stem in record["job_ids"]:
                    target=C.HOME/"remote_logs"/batch/name_path.name
                    target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(z.read(name))
    record.update(status="imported",imported=C.now(),archive=str(archive),outcomes=status,
                  failed_ids=[r["id"] for r in status if r["status"] in ("failed","timeout")])
    C.atomic_json(record_path,record);C.summarize()


