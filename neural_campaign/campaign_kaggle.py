def bundle():
    dest=C.HOME/"kaggle_dataset";dest.mkdir(parents=True,exist_ok=True)
    settings=json.loads((C.HOME/"settings.json").read_text())
    files={C.ROOT/"campaign.py",C.HOME/"jobs.json",C.HOME/"settings.json"}
    files.update((C.HOME/"code"/settings["code_hash"]).glob("*.py"))
    for collection in C.COLLECTIONS:
        root=C.ROOT/collection
        files.add(root/"manifest.json")
        for entry in json.loads((root/"manifest.json").read_text()):
            files.update(root/path for path in entry["files"].values() if isinstance(path,str) and (root/path).is_file())
            files.add(root/"problem"/(entry["problem"]+"__ic.csv"))
        # Also include paired known-BC specs used for evaluation, not training.
        files.update((root/"problem").glob("*.json"))
    with zipfile.ZipFile(dest/"campaign_data.zip","w",zipfile.ZIP_DEFLATED) as z:
        for path in sorted(files):z.write(path,path.relative_to(C.ROOT))
    metadata=dict(title="IE643 frozen neural inversion campaign",id=DATASET,licenses=[dict(name="CC0-1.0")])
    C.atomic_json(dest/"dataset-metadata.json",metadata)
    print(f"Packaged {len(files)} unchanged input/source files; {(dest/'campaign_data.zip').stat().st_size/1e6:.1f} MB")


