    parser=argparse.ArgumentParser(description=__doc__);sub=parser.add_subparsers(dest="action",required=True)
    sub.add_parser("bundle")
    prep=sub.add_parser("prepare");prep.add_argument("--size",type=int,default=12);prep.add_argument("--allow-unpaired",action="store_true")
    imp=sub.add_parser("import");imp.add_argument("batch");imp.add_argument("archive")
    mark=sub.add_parser("mark");mark.add_argument("batch");mark.add_argument("status",choices=["submitted","running","error"])
    args=parser.parse_args()
    if args.action=="bundle":bundle()
    elif args.action=="prepare":prepare(args.size,not args.allow_unpaired)
    elif args.action=="import":ingest(args.batch,args.archive)
    else:
        path=C.HOME/"remote"/(args.batch+".json");r=json.loads(path.read_text());r.update(status=args.status,updated=C.now());C.atomic_json(path,r)


