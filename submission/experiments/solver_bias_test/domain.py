import numpy as np


class Domain2D:
    """Uniform 2D grid on [0, Lx] x [0, Ly]."""

    def __init__(self, Lx=1.0, Ly=1.0, Nx=64, Ny=64):
        self.Lx, self.Ly = Lx, Ly
        self.Nx, self.Ny = Nx, Ny
        self.x = np.linspace(0.0, Lx, Nx)
        self.y = np.linspace(0.0, Ly, Ny)
        self.dx = self.x[1] - self.x[0]
        self.dy = self.y[1] - self.y[0]
        # 'ij' indexing so X[i, j] = x[i], Y[i, j] = y[j]
        self.X, self.Y = np.meshgrid(self.x, self.y, indexing="ij")

    @property
    def shape(self):
        return (self.Nx, self.Ny)

    def flatten(self, field):
        return field.reshape(-1, order="C")

    def unflatten(self, vec):
        return vec.reshape(self.Nx, self.Ny, order="C")


# ---------------------------------------------------------------------
# D(x, y) ground-truth classes - the 5-tier difficulty ladder
# ---------------------------------------------------------------------

def D_tier_A_smooth(domain: Domain2D, D_min=0.05, D_max=0.5):
    """Tier A - smooth sinusoid. Continuous, low-frequency, no sharp
    features anywhere - the sanity-check case both methods should
    recover easily."""
    X, Y = domain.X, domain.Y
    field = 0.5 * (1 + np.sin(2 * np.pi * X) * np.cos(2 * np.pi * Y))
    return D_min + (D_max - D_min) * field


def D_tier_B_gaussian_bump(domain: Domain2D, D_bg=0.08, D_peak=0.5,
                            center=(0.5, 0.5), sigma=0.15):
    """Tier B - a single smooth, localized Gaussian bump. Deliberately
    has NO sharp edge or contrast/sharpness control (unlike Tier C) -
    it isolates "localized feature" difficulty from "sharp interface"
    difficulty, which Tier C tests separately."""
    X, Y = domain.X, domain.Y
    r2 = (X - center[0]) ** 2 + (Y - center[1]) ** 2
    bump = np.exp(-r2 / (2 * sigma ** 2))
    return D_bg + (D_peak - D_bg) * bump


def D_tier_C_inclusion(domain: Domain2D, D_bg=0.08, contrast=7.5,
                        center=(0.5, 0.5), radius=0.15, sharpness=60.0):
    """Tier C - circular inclusion, sharp interface, contrast sweep.
    `contrast` = D_inclusion / D_background (the sweep variable called
    out in the deck); `sharpness` controls how close the tanh-smoothed
    transition is to a true hard edge (higher = crisper interface)."""
    D_inc = D_bg * contrast
    X, Y = domain.X, domain.Y
    r = np.sqrt((X - center[0]) ** 2 + (Y - center[1]) ** 2)
    blend = 0.5 * (1 - np.tanh(sharpness * (r - radius)))
    return D_bg + (D_inc - D_bg) * blend


def D_tier_D_layered_checkerboard(domain: Domain2D, pattern="layered",
                                   values=(0.05, 0.3, 0.6),
                                   boundaries=(0.33, 0.66),
                                   n_blocks=4, D_lo=0.05, D_hi=0.5):
    """Tier D - layered and checkerboard, multiple scales.

    pattern="layered": piecewise-constant stripes along x (`boundaries`
        gives interface x-locations, `values` one D per layer, so
        len(values) == len(boundaries) + 1).
    pattern="checkerboard": alternating D_lo/D_hi blocks on an
        n_blocks x n_blocks grid - `n_blocks` is the "multiple scales"
        control (few large blocks = coarse scale, many small blocks =
        fine scale)."""
    X, Y = domain.X, domain.Y

    if pattern == "layered":
        assert len(values) == len(boundaries) + 1
        field = np.full_like(X, values[0], dtype=float)
        edges = list(boundaries) + [domain.Lx + 1.0]
        for k in range(1, len(values)):
            mask = X >= edges[k - 1]
            field[mask] = values[k]
        return field

    elif pattern == "checkerboard":
        block_x = np.floor(X / domain.Lx * n_blocks).astype(int)
        block_y = np.floor(Y / domain.Ly * n_blocks).astype(int)
        parity = (block_x + block_y) % 2
        return np.where(parity == 0, D_lo, D_hi)

    else:
        raise ValueError(f"Unknown pattern '{pattern}'. Use 'layered' or 'checkerboard'.")


def D_tier_E_gaussian_random_field(domain: Domain2D, D_min=0.05, D_max=0.5,
                                    correlation_length=0.1, seed=None):
    """Tier E - Gaussian random field, correlation length as the dial.
    Generated by spectral filtering: start from spatial white noise,
    multiply its Fourier transform by a Gaussian spectral filter
    exp(-0.5 * |k|^2 * correlation_length^2) (the Fourier transform of a
    Gaussian correlation function), then invert. `correlation_length` is
    a CONTINUOUS difficulty dial - short => rough/high-frequency field
    (harder to recover from sparse sensors, since features are smaller
    than the typical sensor spacing), long => smooth field (easier),
    rather than a fixed set of discrete "true points" like Tiers A-D.
    """
    rng = np.random.default_rng(seed)
    Nx, Ny = domain.Nx, domain.Ny
    white = rng.standard_normal((Nx, Ny))

    kx = np.fft.fftfreq(Nx, d=domain.dx) * 2 * np.pi
    ky = np.fft.fftfreq(Ny, d=domain.dy) * 2 * np.pi
    KX, KY = np.meshgrid(kx, ky, indexing="ij")
    K2 = KX ** 2 + KY ** 2

    spectral_filter = np.exp(-0.5 * K2 * correlation_length ** 2)
    field_hat = np.fft.fft2(white) * spectral_filter
    field = np.real(np.fft.ifft2(field_hat))

    # normalize to zero-mean/unit-std, then squash smoothly into (0,1)
    field = (field - field.mean()) / (field.std() + 1e-12)
    squashed = 1.0 / (1.0 + np.exp(-field))  # sigmoid
    return D_min + (D_max - D_min) * squashed


# ---------------------------------------------------------------------
# Tier F - uniform plate with localised defects
# ---------------------------------------------------------------------
def defect_layout(n_defects=3, radius=0.07, contrast=3.0, kind="mixed", seed=20260908,
                  region=(0.15, 0.85), min_dist=0.25, **_):
    """Deterministic list of defects: dicts with centre (cx, cy), radius r and
    factor = D_defect / D0. kind: 'low' (defect conducts worse, e.g. void,
    porosity, crack), 'high' (conducts better, e.g. metallic inclusion), or
    'mixed' (alternating, starting with low). Centres are drawn uniformly in
    `region` with centre-to-centre distance >= min_dist. Because min_dist does
    not depend on n or radius, layouts are NESTED: the first k centres are the
    same for any n_defects >= k and for any radius, so variants differ only in
    the property being varied."""
    rng = np.random.default_rng(seed)
    centres = []
    tries = 0
    while len(centres) < n_defects:
        c = rng.uniform(region[0], region[1], 2)
        tries += 1
        if all(np.hypot(*(c - p)) >= min_dist for p in centres) or tries > 10000:
            centres.append(c)
    out = []
    for k, (cx, cy) in enumerate(centres):
        low = kind == "low" or (kind == "mixed" and k % 2 == 0)
        out.append(dict(cx=float(cx), cy=float(cy), r=float(radius),
                        factor=float(1 / contrast if low else contrast)))
    return out


def D_tier_F_defects(domain: Domain2D, D0=0.25, n_defects=3, radius=0.07, contrast=3.0,
                     kind="mixed", edge=0.01, seed=20260908):
    """Tier F - a plate of constant diffusivity D0 with a few localised defects.
    Inside each circular spot D is multiplied by its factor (contrast or
    1/contrast); the rim is tanh-smoothed over ~`edge`. Built in log space,
    log D = log D0 + sum_k log(factor_k) * indicator_k, so a defect is a
    multiplicative change and D stays positive."""
    X, Y = domain.X, domain.Y
    m = np.full(X.shape, np.log(D0))
    for d in defect_layout(n_defects, radius, contrast, kind, seed):
        ind = 0.5 * (1 - np.tanh((np.hypot(X - d["cx"], Y - d["cy"]) - d["r"]) / edge))
        m += np.log(d["factor"]) * ind
    return np.exp(m)


D_CLASSES = {
    "A_smooth": D_tier_A_smooth,
    "B_gaussian_bump": D_tier_B_gaussian_bump,
    "C_inclusion": D_tier_C_inclusion,
    "D_layered_checkerboard": D_tier_D_layered_checkerboard,
    "E_gaussian_random_field": D_tier_E_gaussian_random_field,
    "F_defects": D_tier_F_defects,
}

TIER_LABELS = {
    "A_smooth": "Tier A - smooth sinusoid (sanity check)",
    "B_gaussian_bump": "Tier B - Gaussian bump (localized feature)",
    "C_inclusion": "Tier C - circular inclusion (sharp interface, contrast sweep)",
    "D_layered_checkerboard": "Tier D - layered / checkerboard (multiple scales)",
    "E_gaussian_random_field": "Tier E - Gaussian random field (correlation length dial)",
    "F_defects": "Tier F - uniform plate with localised defects (spots of higher/lower D)",
}


def get_D_field(domain: Domain2D, class_name: str, **kwargs):
    if class_name not in D_CLASSES:
        raise ValueError(f"Unknown D(x) class '{class_name}'. "
                          f"Choose from {list(D_CLASSES)}.")
    return D_CLASSES[class_name](domain, **kwargs)
